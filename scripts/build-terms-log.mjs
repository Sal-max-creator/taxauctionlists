// Writes SOURCES.md: every source page, what it backs, when it was read, and its reuse terms.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { readStateFiles } from "./lib/data.mjs";
import { LINK_ONLY_HOSTS } from "./lib/rules.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const linkOnly = JSON.parse(fs.readFileSync(path.join(root, "src/_data/linkOnly.json"), "utf8"));
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

const out = [
  "# Source and terms log",
  "",
  "Generated by `npm run terms-log` from `data/states/*.json`. Do not edit by hand.",
  "",
  "Rules: sale dates come only from county or state government pages, or legally required notices, that we actually read. Private auction platforms and sources whose terms forbid reuse are link-only: we link to them and never copy their parcel data.",
  "",
  "## Link-only sources",
  "",
  "| Source | Why | Checked |",
  "|---|---|---|",
  ...linkOnly.map((s) => `| [${cell(s.name)}](${s.url}) | ${cell(s.why)} | ${s.checked} |`),
  "",
  `Hosts the validator refuses as a sale source: ${LINK_ONLY_HOSTS.map((h) => `\`${h}\``).join(", ")}.`,
  "",
];

for (const { data } of readStateFiles().sort((a, b) => a.data.name.localeCompare(b.data.name))) {
  out.push(`## ${data.name}`, "");
  if ((data.overview_sources || []).length) {
    out.push("State overview: " + data.overview_sources.map((s) => `<${s.url}>`).join(", "), "");
  }
  out.push("| County | Source page | Read on | Reuse terms |", "|---|---|---|---|");
  for (const c of data.counties || []) {
    for (const s of c.sources || []) {
      const terms = s.terms_url ? `${cell(s.terms)} ([terms](${s.terms_url}))` : cell(s.terms || "not recorded");
      out.push(`| ${cell(c.county)} | <${s.url}> | ${s.read_on} | ${terms} |`);
    }
  }
  out.push("");
}

fs.writeFileSync(path.join(root, "SOURCES.md"), out.join("\n"));
console.log("Wrote SOURCES.md");
